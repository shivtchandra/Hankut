/**
 * Helper to find a person in the catalog by exact or normalized name/alias
 */
export function findPersonInCatalog(query: string): CatalogPerson | undefined {
  if (!query) return undefined;
  const q = query.toLowerCase().trim().replace(/[\s\-_'".]/g, "");
  if (!q) return undefined;

  for (const person of PEOPLE_CATALOG) {
    const en = person.nameEn.toLowerCase().replace(/[\s\-_'".]/g, "");
    const kr = person.nameKr.toLowerCase().replace(/[\s\-_'".]/g, "");
    if (en === q || kr === q) return person;
    for (const alias of person.aliases || []) {
      const a = alias.toLowerCase().replace(/[\s\-_'".]/g, "");
      if (a === q) return person;
    }
  }
  return undefined;
}
