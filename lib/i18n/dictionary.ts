export function localizeClueLabel(raw: string, locale: Locale) {
  const key = raw.trim().toLowerCase();
  const hit =
    clueLabelMap[raw] ??
    clueLabelMap[key] ??
    Object.entries(clueLabelMap).find(([k]) => k.toLowerCase() === key)?.[1];
  if (hit) return hit[locale];
  return raw;
}

export function puzzleTypeLabel(
  type: string,
  locale: Locale,
): string {
  const map: Record<string, DictionaryKey> = {
    scene: "typeScene",
    song: "typeSong",
    chosung: "typeChosung",
    connections: "typeConnections",
    people: "typePeople",
  };
  const key = map[type] ?? "typeScene";
  return dictionaries[locale][key];
}
